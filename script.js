// دالة بدء اللعبة التي يتم استدعاؤها عند الضغط على الزر في الـ HTML
function startGame() {
    // 1. طباعة رسالة في الـ Console للتأكد من أن الزر يستجيب
    console.log("تم الضغط على زر تشغيل اللعبة بنجاح! السيرفر يعمل.");

    // 2. تغيير النص الموجود في الصفحة لتأكيد التشغيل أمام المستخدم
    let statusElement = document.getElementById("game-status");
    statusElement.innerHTML = "🚀 تم تشغيل اللعبة بنجاح! الزر يعمل الآن.";
    statusElement.style.color = "#28a745"; // تغيير اللون للأخضر

    // 3. تنبيه سريع يظهر على الشاشة
    alert("مرحباً بك! تم تشغيل اللعبة بدون أخطاء.");
}
